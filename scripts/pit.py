#!/usr/bin/env python3
"""Run PIT mutation testing and save the report as evidence. Never type a score by hand.

  python scripts/pit.py before                run PIT now, save docs/mutation/before/ and before.txt
  python scripts/pit.py before --at <commit>  rebuild "before" from an earlier commit (for example the step 3 commit),
                                              in a temporary worktree: use this if step 4 was already done
  python scripts/pit.py after                 run PIT now, save docs/mutation/after/ and after.txt
  python scripts/pit.py show                  print the saved scores

Each run also updates the table in docs/mutation-testing.md and writes the before and after scores as text into
ASSIGNMENT.md (both between the pit:begin and pit:end markers).
"before" must be saved first and is never overwritten (use --force to redo it). The command is
`mvn -B -q test-compile org.pitest:pitest-maven:mutationCoverage`; override with the PIT_CMD environment variable.
"""
import argparse, collections, datetime, glob, os, re, shutil, subprocess, sys, tempfile
sys.dont_write_bytecode = True
import xml.etree.ElementTree as ET

OUT = os.path.join("docs", "mutation")
DOC = os.path.join("docs", "mutation-testing.md")
ASSIGNMENT = "ASSIGNMENT.md"
BEGIN, END = "<!-- pit:begin (generated by scripts/pit.py, do not edit) -->", "<!-- pit:end -->"
CMD = os.environ.get("PIT_CMD", "mvn -B -q test-compile org.pitest:pitest-maven:mutationCoverage")
DETECTED = ("KILLED", "TIMED_OUT", "MEMORY_ERROR")


def sh(*args, cwd=None):
    r = subprocess.run(args, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def find_report(root):
    """Return the folder holding mutations.xml (target/pit-reports, or the newest timestamped subfolder)."""
    direct = os.path.join(root, "target", "pit-reports", "mutations.xml")
    if os.path.exists(direct):
        return os.path.dirname(direct)
    found = glob.glob(os.path.join(root, "target", "pit-reports", "**", "mutations.xml"), recursive=True)
    return os.path.dirname(max(found, key=os.path.getmtime)) if found else None


def read_mutations(folder):
    counts, survivors = collections.Counter(), []
    for node in ET.parse(os.path.join(folder, "mutations.xml")).getroot().iter("mutation"):
        status = node.get("status", "UNKNOWN")
        counts[status] += 1
        if status in ("SURVIVED", "NO_COVERAGE"):
            survivors.append((node.findtext("mutatedClass", "?").split(".")[-1], node.findtext("mutatedMethod", "?"),
                              node.findtext("lineNumber", "?"), node.findtext("mutator", "?").split(".")[-1],
                              node.findtext("description", "").strip(), status))
    detected = sum(counts[s] for s in DETECTED)
    total = sum(counts.values()) - counts["NON_VIABLE"]
    return {"counts": counts, "detected": detected, "total": total, "survivors": survivors,
            "percent": round(100.0 * detected / total, 1) if total else 0.0}


def run_pit(cwd):
    print(f"running PIT in {os.path.abspath(cwd)}: {CMD}\n(this can take a few minutes)", flush=True)
    r = subprocess.run(CMD, shell=True, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    report = find_report(cwd)
    if r.returncode != 0 or not report:
        print("\n".join(r.stdout.splitlines()[-30:]))
        sys.exit("PIT did not produce a report. Check that `mvn test` passes first (PIT needs green tests). "
                 "The report must be at target/pit-reports/mutations.xml.")
    return report


def save(label, report, rev):
    dest = os.path.join(OUT, label)
    os.makedirs(OUT, exist_ok=True)
    if os.path.exists(dest):
        shutil.rmtree(dest)
    shutil.copytree(report, dest)
    m = read_mutations(dest)
    lines = [f"PIT {label}: {m['detected']} of {m['total']} mutants killed = {m['percent']} percent",
             f"survived: {m['counts']['SURVIVED']}, not covered by any test: {m['counts']['NO_COVERAGE']}, "
             f"timed out: {m['counts']['TIMED_OUT']}, non-viable (ignored): {m['counts']['NON_VIABLE']}",
             f"commit: {rev or 'unknown'}   saved: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')}",
             "formula: killed (incl. timed out) / all mutants except non-viable. The PIT HTML report (index.html in this folder) is authoritative.",
             "", "Mutants to kill with new tests (class.method:line, mutator, what changed):"]
    lines += [f"- {c}.{meth}:{ln} {mut} - {desc} [{st}]" for c, meth, ln, mut, desc, st in m["survivors"][:40]] or ["- none"]
    with open(os.path.join(OUT, f"{label}.txt"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("\n".join(lines[:4]))
    return m


def replace_block(path, heading, block, create_header=""):
    """Put block between the pit markers in path. Without markers, replace the body of `heading`, or append it."""
    text = open(path, encoding="utf-8").read() if os.path.exists(path) else create_header
    if BEGIN in text and END in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    elif heading in text:
        start = text.index(heading) + len(heading)
        nxt = text.find("\n## ", start)
        text = text[:start] + "\n\n" + block + "\n" + (text[nxt:] if nxt != -1 else "")
    else:
        text = text.rstrip() + f"\n\n{heading}\n\n" + block + "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def pom_version():
    try:
        pom = open("pom.xml", encoding="utf-8").read()
        return re.search(r"pitest-maven</artifactId>\s*<version>([^<]+)</version>", pom).group(1)
    except Exception:
        return "unknown"


def summaries():
    """label -> (mutation result or None, 'commit, date' meta text)."""
    out = {}
    for label in ("before", "after"):
        folder = os.path.join(OUT, label)
        if os.path.exists(os.path.join(folder, "mutations.xml")):
            txt = open(os.path.join(OUT, f"{label}.txt"), encoding="utf-8").read().splitlines()
            out[label] = (read_mutations(folder), txt[2].replace("commit: ", "").replace("   saved: ", ", saved "))
        else:
            out[label] = (None, "")
    return out


def update_doc():
    data = summaries()
    rows = []
    for label, (m, meta) in data.items():
        rows.append(f"| {label.capitalize()} | {m['detected']} of {m['total']} | {m['percent']} percent | {m['counts']['SURVIVED']} | {m['counts']['NO_COVERAGE']} | {meta.split(', saved')[0]} |"
                    if m else f"| {label.capitalize()} | not generated | | | | |")
    block = "\n".join([BEGIN, "", "| Run | Killed | Score | Survived | Not covered | Commit |", "| --- | --- | --- | --- | --- | --- |"] + rows +
                      ["", "Details and the list of surviving mutants: `docs/mutation/before.txt`, `docs/mutation/after.txt`. "
                       "Full HTML reports: `docs/mutation/before/index.html`, `docs/mutation/after/index.html`.", "", END])
    replace_block(DOC, "## Scores (generated)", block, "# Mutation testing\n")
    update_assignment(data)


def update_assignment(data=None):
    """Write the before and after scores as plain text into ASSIGNMENT.md (required by the assignment)."""
    data = data or summaries()
    lines = []
    for label, (m, meta) in data.items():
        head = f"{label.capitalize()}:" + (" " if label == "before" else "  ")
        lines.append(f"{head}{m['detected']} of {m['total']} mutants killed = {m['percent']} percent "
                     f"({m['counts']['SURVIVED']} survived, {m['counts']['NO_COVERAGE']} not covered by any test) [commit {meta}]" if m
                     else f"{head}NOT GENERATED yet. Run: python scripts/pit.py {label}")
    block = "\n".join([BEGIN, "", "```text", f"Tool: PIT (pitest-maven {pom_version()}), default mutators, classes in the domain package, run by scripts/pit.py"] + lines +
                      ["```", "", "Reports and surviving-mutant lists: `docs/mutation/` (see also `docs/mutation-testing.md`). This block is written by `scripts/pit.py`; do not retype it.", "", END])
    replace_block(ASSIGNMENT, "## Mutation scores (text)", block, "")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("label", choices=["before", "after", "show"])
    ap.add_argument("--at", metavar="COMMIT", help="run on this earlier commit in a temporary worktree (before only)")
    ap.add_argument("--force", action="store_true", help="overwrite an existing 'before', or run 'after' without a 'before'")
    args = ap.parse_args()

    if args.label == "show":
        for label in ("before", "after"):
            path = os.path.join(OUT, f"{label}.txt")
            print(open(path, encoding="utf-8").read().split("\n\n")[0] if os.path.exists(path) else f"{label}: not generated")
            print()
        return
    have_before = os.path.exists(os.path.join(OUT, "before", "mutations.xml"))
    if args.label == "before" and have_before and not args.force:
        sys.exit("docs/mutation/before already exists and must not be replaced by a newer run. Use --force only if you are sure.")
    if args.label == "after" and not have_before and not args.force:
        sys.exit("Run `python scripts/pit.py before` first (or `--at <commit>` to rebuild it from before the test changes).")
    if args.at and args.label != "before":
        sys.exit("--at only makes sense for 'before'")

    if args.at:
        rev = sh("git", "rev-parse", "--short", args.at)
        if not rev:
            sys.exit(f"unknown commit: {args.at}")
        tmp = tempfile.mkdtemp(prefix="pit-before-")
        wt = os.path.join(tmp, "wt")
        if subprocess.run(["git", "worktree", "add", "--detach", wt, rev], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode != 0:
            sys.exit("could not create a temporary git worktree")
        try:
            report = run_pit(wt)
            save("before", report, f"{rev} (built in a temporary worktree)")
        finally:
            subprocess.run(["git", "worktree", "remove", "--force", wt], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            shutil.rmtree(tmp, ignore_errors=True)
    else:
        report = run_pit(".")
        dirty = " (uncommitted changes present)" if sh("git", "status", "--porcelain") else ""
        save(args.label, report, (sh("git", "rev-parse", "--short", "HEAD") or "unknown") + dirty)
    update_doc()
    print(f"saved docs/mutation/{args.label}.txt and updated {DOC}")


if __name__ == "__main__":
    main()
